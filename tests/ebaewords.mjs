// Builds site/js/ebaewords.js: the common words whose pre-UEB (EBAE) braille differs from UEB, from liblouis's
// EBAE table (en-us-g2.ctb). Braille to text uses it to offer pre-UEB readings.
// Run: node tests/ebaewords.mjs   (needs liblouis: apt-get install liblouis-bin liblouis-data)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { COMMON_WORDS } from '../site/js/wordlist.js';
import { translate, unicodeOf } from '../site/js/braille.js';

export const FILE = fileURLToPath(new URL('../site/js/ebaewords.js', import.meta.url));
export function build() {
  // Single letters are left out: EBAE marks a lone letter with a letter sign, which isn't a word reading.
  const words = COMMON_WORDS.filter((w) => w.length > 1);
  const lou = execFileSync('lou_translate', ['--forward', 'unicode.dis,en-us-g2.ctb'], { input: words.join('\n') + '\n' }).toString().split('\n');
  const pairs = words.map((w, i) => [w, lou[i]]).filter(([w, e]) => e && e !== unicodeOf(translate(w, 'en', 2)));
  return `// Generated by tests/ebaewords.mjs from liblouis en-us-g2.ctb: common words whose pre-UEB (EBAE) braille differs from UEB.
// "word=cells", most common first. Don't edit by hand.
export const EBAE_WORDS = '${pairs.map(([w, e]) => `${w}=${e}`).join(' ')}'.split(' ').map((x) => x.split('='));
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) { writeFileSync(FILE, build()); console.log('wrote', FILE); }
